import "server-only";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";

// File storage on local disk, outside the deployed app folder so redeploys don't wipe
// uploads. Two areas:
//   originals/  private uploads, served only to the admin (/admin/originals/…)
//   public/     watermarked WebP copies, served at /media/…
// To move to S3 / Cloudflare R2 later, reimplement these three functions.
// (turbopackIgnore: these are runtime data paths, not files to trace into the build.)

export type Bucket = "originals" | "public";

// Keys are generated by the app: "<uuid>.webp" or "<uuid>/<uuid>.<ext>".
const KEY_RE = /^(?:[0-9a-f-]{36}\/)?[0-9a-f-]{36}\.[a-z0-9]{2,5}$/;

export function isValidKey(key: string) {
  return KEY_RE.test(key);
}

function root() {
  const dir = process.env.UPLOAD_DIR;
  if (dir) return path.resolve(/*turbopackIgnore: true*/ dir);
  if (process.env.NODE_ENV === "production") throw new Error("UPLOAD_DIR must be set in production");
  return path.resolve(/*turbopackIgnore: true*/ process.cwd(), ".uploads");
}

function filePath(bucket: Bucket, key: string) {
  if (!isValidKey(key)) throw new Error(`invalid storage key: ${key}`);
  return path.join(/*turbopackIgnore: true*/ root(), bucket, key);
}

export async function putFile(bucket: Bucket, key: string, data: Buffer) {
  const p = filePath(bucket, key);
  await mkdir(/*turbopackIgnore: true*/ path.dirname(p), { recursive: true });
  // "wx": never overwrite an existing file.
  await writeFile(/*turbopackIgnore: true*/ p, data, { flag: "wx", mode: 0o640 });
}

export async function readStoredFile(bucket: Bucket, key: string) {
  try {
    return await readFile(/*turbopackIgnore: true*/ filePath(bucket, key));
  } catch {
    return null;
  }
}

export async function removeFile(bucket: Bucket, key: string) {
  if (!isValidKey(key)) return;
  await rm(/*turbopackIgnore: true*/ filePath(bucket, key), { force: true });
}
