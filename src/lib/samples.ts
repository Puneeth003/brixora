// Fixed reference date so demo data renders identically on every request.
const REF_DATE = Date.parse("2026-10-26T06:00:00Z");

export const sampleProperties: PublicProperty[] = SAMPLES.map(({ key, photos, daysAgo, ...p }) => {
  void photos;
  const at = new Date(REF_DATE - daysAgo * 86_400_000).toISOString();
  return { ...p, cover_path: `/samples/${key}-1.webp`, approved_at: at, verified_at: at, updated_at: at };
});

