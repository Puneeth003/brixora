// Builds db/seed.sql from src/lib/samples.ts so demo data matches the local preview.
// Run: node scripts/generate-seed.mjs   (Node 22.6+ strips the TypeScript types)
import fs from "node:fs";
import { sampleImages, sampleProperties } from "../src/lib/samples.ts";

const q = (v) =>
  v === null || v === undefined
    ? "NULL"
    : typeof v === "number"
      ? String(v)
      : typeof v === "boolean"
        ? (v ? "1" : "0")
        : `'${String(v).replace(/\\/g, "\\\\").replace(/'/g, "''")}'`;
// ISO timestamp → MySQL DATETIME literal (UTC).
const ts = (iso) => q(iso.replace("T", " ").replace("Z", ""));
const OWNER = "00000000-0000-4000-8000-0000000000aa";
const BUILDER = "00000000-0000-4000-8000-0000000000b1";
const PROJECT = "00000000-0000-4000-8000-0000000000c1";

let sql = `-- Demo data for Brixora (generated by scripts/generate-seed.mjs — do not edit by hand).
-- Images point at /samples/*.webp which ship with the app.
-- Apply after db/schema.sql:  mysql -h HOST -u USER -p DBNAME < db/seed.sql
-- Remove before launch:
--   DELETE FROM properties WHERE owner_id = '${OWNER}';
--   DELETE FROM users WHERE id = '${OWNER}';
--   DELETE FROM builders WHERE id = '${BUILDER}';

SET NAMES utf8mb4;
SET time_zone = '+00:00';

INSERT IGNORE INTO users (id, role, name, phone, phone_verified_at)
VALUES ('${OWNER}', 'owner', 'Demo Owner', '919999900000', UTC_TIMESTAMP(3));

INSERT IGNORE INTO builders (id, name, rera_no, contact_name)
VALUES ('${BUILDER}', 'Coastal Homes', 'PRM/KA/RERA/1257/334/AG/000000', 'Sales office');
INSERT IGNORE INTO projects (id, builder_id, name, locality, rera_no, status)
VALUES ('${PROJECT}', '${BUILDER}', 'Coastal Greens', 'Kadri', 'PRM/KA/RERA/1257/334/PR/210901/004321', 'ready');
`;

for (const p of sampleProperties) {
  const linked = p.project_name ? `'${BUILDER}', '${PROJECT}'` : "NULL, NULL";
  sql += `
INSERT IGNORE INTO properties (id, reference_no, status, listing_type, property_type, title, description, price, price_negotiable,
  locality, city, private_address, bedrooms, bathrooms, area_sqft, furnishing, floor, property_age, available_from, amenities,
  builder_id, project_id, featured, owner_id, submitted_at, approved_at, expires_at)
VALUES (${q(p.id)}, ${q(p.reference_no)}, 'approved', ${q(p.listing_type)}, ${q(p.property_type)}, ${q(p.title)}, ${q(p.description)},
  ${p.price}, ${q(p.price_negotiable)}, ${q(p.locality)}, ${q(p.city)}, 'Demo address (sample listing)', ${q(p.bedrooms)}, ${q(p.bathrooms)},
  ${q(p.area_sqft)}, ${q(p.furnishing)}, ${q(p.floor)}, ${q(p.property_age)}, ${q(p.available_from)}, ${q(JSON.stringify(p.amenities))},
  ${linked}, ${q(p.featured)}, '${OWNER}', ${ts(p.approved_at)}, ${ts(p.approved_at)}, DATE_ADD(${ts(p.approved_at)}, INTERVAL 90 DAY));
`;
  for (const img of sampleImages[p.id]) {
    sql += `INSERT IGNORE INTO property_images (id, property_id, storage_path, watermarked_path, sort_order, is_cover, is_visible, approved)
VALUES (${q(img.id)}, ${q(p.id)}, ${q(`demo${img.watermarked_path}`)}, ${q(img.watermarked_path)}, ${img.sort_order}, ${q(img.is_cover)}, 1, 1);
`;
  }
}

sql += `
-- Keep new reference numbers after the demo ones.
UPDATE app_config SET value = GREATEST(CAST(value AS UNSIGNED), ${sampleProperties.length}) WHERE name = 'ref_seq';
`;
fs.mkdirSync("db", { recursive: true });
fs.writeFileSync("db/seed.sql", sql);
console.log(`wrote db/seed.sql (${sampleProperties.length} properties)`);
